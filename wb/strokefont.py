ADV={'I':2.8,'1':3.6,'!':1.8,"'":1.4,'.':1.4,',':1.4,':':1.4,' ':2.4,'/':3.6,'-':3.6}
def width(t,size):
    u=size/6.0*0.82;return sum((ADV.get(c,5.0))*u for c in t.upper())-1.0*u
def strokes(t,x,y,size):
    """centred at (x,y); size = cap height in px"""
    u=size/6.0*0.82;h=6*u;cx=x-width(t,size)/2;out=[]
    for c in t.upper():
        for pl in G.get(c,[]):
            out.append([(cx+px*u,y-h/2+py*u) for px,py in pl])
        cx+=ADV.get(c,5.0)*u
    return out
